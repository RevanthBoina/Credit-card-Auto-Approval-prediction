'use client'

import { useEffect, useState } from 'react'
import { Sparkles, Loader2, AlertCircle } from 'lucide-react'
import { Card, CardContent } from '@/components/ui/card'

const STORAGE_KEY = 'credit_card_form_data'

type ExplainResponse = {
  success: boolean
  source?: 'ai' | 'rules'
  explanation?: string
  error?: string
}

export default function RejectionAssistant({ probability }: { probability: number }) {
  const [explanation, setExplanation] = useState<string | null>(null)
  const [source, setSource] = useState<'ai' | 'rules' | null>(null)
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState(false)

  useEffect(() => {
    let cancelled = false

    async function load() {
      // Read the applicant's submitted values saved by the predict form.
      let applicant: Record<string, unknown> = {}
      try {
        const raw = sessionStorage.getItem(STORAGE_KEY)
        if (raw) applicant = JSON.parse(raw)
      } catch {
        applicant = {}
      }

      try {
        const resp = await fetch('/api/explain', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ ...applicant, probability }),
        })
        const data: ExplainResponse = await resp.json()
        if (cancelled) return
        if (data.success && data.explanation) {
          setExplanation(data.explanation)
          setSource(data.source ?? null)
        } else {
          setError(true)
        }
      } catch {
        if (!cancelled) setError(true)
      } finally {
        if (!cancelled) setLoading(false)
      }
    }

    load()
    return () => {
      cancelled = true
    }
  }, [probability])

  return (
    <Card className="border-primary/20">
      <CardContent className="pt-6">
        <div className="mb-3 flex items-center gap-2">
          <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-primary/10">
            <Sparkles className="h-4 w-4 text-primary" />
          </div>
          <div>
            <h2 className="text-sm font-semibold">AI Assistant</h2>
            <p className="text-xs text-muted-foreground">Why this was likely rejected</p>
          </div>
        </div>

        {loading ? (
          <div className="flex items-center gap-2 text-sm text-muted-foreground">
            <Loader2 className="h-4 w-4 animate-spin" />
            Analyzing your application…
          </div>
        ) : error ? (
          <div className="flex items-start gap-2 text-sm text-muted-foreground">
            <AlertCircle className="mt-0.5 h-4 w-4 shrink-0" />
            <span>
              Couldn&apos;t generate an explanation right now. The main negative factors are usually a prior
              default, low income, high debt, or short employment history.
            </span>
          </div>
        ) : (
          <div className="space-y-2">
            <p className="text-sm leading-relaxed text-foreground/90 whitespace-pre-line">{explanation}</p>
            {source === 'ai' ? (
              <p className="text-[11px] text-muted-foreground">Generated by AI · educational guidance only</p>
            ) : (
              <p className="text-[11px] text-muted-foreground">Rule-based estimate · educational guidance only</p>
            )}
          </div>
        )}
      </CardContent>
    </Card>
  )
}
